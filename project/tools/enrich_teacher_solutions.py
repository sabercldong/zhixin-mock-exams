START = "<!-- teacher-only-start -->"
END = "<!-- teacher-only-end -->"


def split_problems(text: str) -> tuple[str, list[tuple[str, str]]]:
    pattern = re.compile(r"(?m)^# 第 (\d+) 题\s*$")
    matches = list(pattern.finditer(text))
    if len(matches) != 8:
        raise RuntimeError(f"expected 8 problems, found {len(matches)}")
    prefix = text[: matches[0].start()]
    blocks: list[tuple[str, str]] = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        blocks.append((match.group(1), text[match.start() : end].rstrip()))
    return prefix, blocks


def enrich_block(set_number: str, question: int, block: str) -> str:
    block = re.sub(
        rf"(?s)\n*{re.escape(START)}.*?{re.escape(END)}\s*",
        "\n\n",
        block,
    )
    marker = "## 六、关键洞察"
    position = block.find(marker)
    if position < 0:
        raise RuntimeError(f"蔡题{set_number}第{question}题缺少关键洞察标题")
    audit = AUDITS[set_number][question].strip()
    insertion = f"{START}\n{audit}\n{END}\n\n"
    return block[:position].rstrip() + "\n\n" + insertion + block[position:]


def main() -> None:
    selected = sys.argv[1:] or list(AUDITS)
    unknown = [item for item in selected if item not in AUDITS]
    if unknown:
        raise RuntimeError(f"未定义教师补充解析的套号：{', '.join(unknown)}")
    for set_number in selected:
        audits = AUDITS[set_number]
        if set(audits) != set(range(1, 9)):
            raise RuntimeError(f"蔡题{set_number}补充解析题号不完整")
        path = (
            ROOT
            / f"蔡题{set_number}"
            / "整理版"
            / "markdown"
            / f"蔡题{set_number}_教师备课.md"
        )
        prefix, blocks = split_problems(path.read_text(encoding="utf-8"))
        enriched = [
            enrich_block(set_number, int(question), block)
            for question, block in blocks
        ]
        path.write_text(prefix + "\n\n".join(enriched).rstrip() + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
